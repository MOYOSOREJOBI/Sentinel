function resolveLocale(input: string | null | undefined): Locale {
  const next = String(input || 'en') as Locale
  return locales.includes(next) ? next : 'en'
}

export function applyLocale(locale: string) {
  if (typeof document === 'undefined') return
  const safe = resolveLocale(locale)
  document.documentElement.lang = safe
  document.documentElement.dir = safe.startsWith('ar') ? 'rtl' : 'ltr'
  localStorage.setItem(STORAGE_KEY, safe)
  document.cookie = `locale=${safe}; Path=/; Max-Age=31536000; SameSite=Lax`
  window.dispatchEvent(new CustomEvent(LOCALE_EVENT, { detail: safe }))
}

export function localeFromStorage(): Locale {
  if (typeof window === 'undefined') return 'en'
  return resolveLocale(localStorage.getItem(STORAGE_KEY))
}

export function setLocaleStorage(locale: Locale) {
  if (typeof window === 'undefined') return
  applyLocale(locale)
}

export function t(locale: Locale, key: string, fallback: string): string {
  return dictionaries[locale]?.[key] ?? fallback
}

export function allLocales(): Locale[] {
  return locales
}

export function localeLabel(locale: Locale): string {
  try {
    const display = new Intl.DisplayNames([locale], { type: 'language' })
    const value = display.of(locale)
    if (value) return value
  } catch {
    // fall through to manual autonym map
  }
  return localeAutonymFallback[locale] || locale
}

export function useLocale(): [Locale, (next: Locale) => void] {
  const [locale, setLocale] = useState<Locale>('en')

  useEffect(() => {
    const sync = () => setLocale(localeFromStorage())
    sync()
    window.addEventListener(LOCALE_EVENT, sync as EventListener)
    window.addEventListener('storage', sync)
    return () => {
      window.removeEventListener(LOCALE_EVENT, sync as EventListener)
      window.removeEventListener('storage', sync)
    }
  }, [])

  const update = (next: Locale) => setLocaleStorage(next)
  return [locale, update]
}

export function useI18n() {
  const [locale, setLocale] = useLocale()
  const tr = useMemo(() => (key: string, fallback: string) => t(locale, key, fallback), [locale])
  return { locale, setLocale, tr }
}
